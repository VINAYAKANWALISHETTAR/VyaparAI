    if (args != null && args.isNotEmpty) {
      for (final entry in args.entries) {
        template = template!.replaceAll('{${entry.key}}', entry.value.toString());
      }
    }

    return template ?? key;
  }

  static bool hasKey(String key, [String? langCode]) {
    final code = (langCode ?? 'EN').toUpperCase();
    return _values[code]?.containsKey(key) ?? false;
  }
}

final appTranslationsProvider = Provider<String Function(String, [Map<String, dynamic>?])>((ref) {
  final lang = ref.watch(languageProvider);
  return (String key, [Map<String, dynamic>? args]) =>
      AppTranslations.get(key, lang.code, args);
});

extension TranslationContext on BuildContext {
  String tr(String key, [Map<String, dynamic>? args]) {
    // Convenience helper
    return AppTranslations.get(key, 'EN', args);
  }
}
